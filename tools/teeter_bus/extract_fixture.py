#!/usr/bin/env python3
"""Extract the committed production Teeter bus spans into a mixed HDL fixture."""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CORE = ROOT / "rtl" / "Exidy2.v"


def span(source: str, start: str, end: str, label: str) -> str:
    i = source.find(start)
    if i < 0:
        raise SystemExit(f"FAIL source extraction: missing {label} start marker")
    j = source.find(end, i + len(start))
    if j < 0:
        raise SystemExit(f"FAIL source extraction: missing {label} end marker")
    return source[i:j].rstrip()


def extract() -> tuple[str, str]:
    source = CORE.read_text(encoding="utf-8")
    declarations = span(
        source, "reg  [7:0]  CPU_databus_in;", "wire nWM2V", "CPU data and Teeter ESR declarations"
    )
    declarations = declarations.replace("reg  [7:0]  CPU_databus_in;", "")
    declarations = declarations.replace("wire [7:0]  CPU_databus_out;", "")
    declarations = declarations.replace("reg  [7:0] EIR;", "")
    pending = span(
        source,
        "// The byte mux is registered every master edge",
        "teeterControls TEETER_CONTROLS(",
        "registered Teeter read qualifier",
    )
    controls_start = source.find("teeterControls TEETER_CONTROLS(")
    if controls_start < 0:
        raise SystemExit("FAIL source extraction: missing production Teeter controls instance")
    controls_end = source.find("\n);", controls_start)
    if controls_end < 0:
        raise SystemExit("FAIL source extraction: unterminated production Teeter controls instance")
    controls = source[controls_start : controls_end + 3]
    # Connect the real production instance's otherwise-open observation outputs
    # so the fixture can assert its state without changing functional RTL.
    controls = controls.replace(".dial_position(),", ".dial_position(dial_position),")
    controls = controls.replace(".dial_consumed(),", ".dial_consumed(dial_consumed),")
    controls = controls.replace(".in0_value(teeter_in0)", ".in0_value(teeter_in0)")
    mux_start = source.find("//CPU read selection logic")
    if mux_start < 0:
        raise SystemExit("FAIL source extraction: missing production CPU read mux marker")
    mux_start = source.find("always @(posedge master_clock) begin", mux_start)
    mux_end = source.find("\nend", mux_start)
    if mux_start < 0 or mux_end < 0:
        raise SystemExit("FAIL source extraction: missing production CPU read mux block")
    mux = source[mux_start : mux_end + len("\nend")]

    header = r'''`timescale 1ns/1ps
// Generated by tools/teeter_bus/extract_fixture.py from committed rtl/Exidy2.v.
module teeterProductionBus (
    input wire master_clock, RESET_n, PH_1, pause, ce_frame, dpad_pos_mode,
    input wire [8:0] spinner,
    input wire signed [7:0] analog_x,
    input wire m_right, m_left, m_down, m_up, m_fire, m_start1p, m_start2p, m_coina, m_coinb,
    input wire [7:0] pcb, DIP1,
    input wire [23:0] CPU_addrbus,
    input wire CPU_RWn,
    input wire [7:0] CPU_databus_out,
    input wire RAMSEL, ROMSEL, SRAMSEL, CHARSEL, EXTVID, IOSEL,
    input wire [7:0] CPU_RAM_out, CPU_PROM_out, VRAM_CPU_out,
    input wire [7:0] VRAM_out_CSCG1_CPU, VRAM_out_CSCG2_CPU,
    input wire [7:0] EIR, audio_data_out, IN2,
    output reg [7:0] CPU_databus_in,
    output wire [7:0] dial_position, dial_consumed
);
'''
    return header + declarations + "\n" + pending + "\n" + controls + "\n" + mux + "\nendmodule\n", hashlib.sha256(source.encode()).hexdigest()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--output", required=True, type=Path)
    args = ap.parse_args()
    generated, digest = extract()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generated, encoding="utf-8")
    print(f"PASS extracted production teeter bus spans; rtl/Exidy2.v sha256={digest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
