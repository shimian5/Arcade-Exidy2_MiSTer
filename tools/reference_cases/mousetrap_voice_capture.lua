-- Passive Mouse Trap digital-voice capture. Only observes native CPU buses;
-- all game controls use declared MAME input fields.
local m = manager.machine
local main = assert(m.devices[":maincpu"])
local mainspace = assert(main.spaces["program"])
local audio = assert(m.devices[":soundbd:audiocpu"])
local audiospace = assert(audio.spaces["program"])
local z80 = assert(m.devices[":soundbd:cvsdcpu"])
local iospace = assert(z80.spaces["io"])
local screen = assert(m.screens[":screen"])
local limit = tonumber(os.getenv("MTRAP_VOICE_FRAMES") or "7200")
local output = assert(io.open(assert(os.getenv("MTRAP_VOICE_OUT")), "w"))
local events = assert(io.open(assert(os.getenv("MTRAP_VOICE_EVENTS")), "w"))
local taps, counts = {}, {}
local frames = 0

local function pc(cpu)
 local r = cpu.state["PC"]
 return r and (r.value & 0xffff) or 0xffff
end
local function log(kind, cpu, address, data, mask, bus, keep)
 local f = screen:frame_number()
 local key = kind .. ":" .. bus
 counts[key] = (counts[key] or 0) + 1
 if not keep then return end
 output:write(string.format("%s,%s,%d,%.9f,%04X,%04X,%02X,%X\n", kind, bus, f, m.time:as_double(), pc(cpu), address & 0xffff, data & 0xff, mask or 0xff))
 counts[key .. ":saved"] = (counts[key .. ":saved"] or 0) + 1
end

output:write("kind,bus,frame,time_s,pc,address,data,mask\n")
events:write("set=mtrap tap=passive native maincpu/audio6502/Z80 buses; frame_limit=" .. limit .. "\n")
events:write("audio_riot_tap=program 0800-0fff (RIOT I/O mirrored); z80_io_tap=IO 00-ff; no injected commands or firmware changes\n")

-- Mouse Trap voice Z80 uses standard I/O reads for the command/status nibble
-- and CVSD clock, and writes with A4/A5 low for digit and busy handshakes.
taps[#taps+1] = iospace:install_read_tap(0x00, 0xff, "mtrap_voice_io_read", function(a,d,mask) log("R", z80, a,d,mask,"z80io",(a & 0xc0)~=0xc0) end)
taps[#taps+1] = iospace:install_write_tap(0x00, 0xff, "mtrap_voice_io_write", function(a,d,mask) log("W", z80,a,d,mask,"z80io",(a & 0x30)~=0x30) end)
-- 6532 ORA/DDRA writes carry CVSD data/reset and handshake control. Keep the
-- full mirrored range so the address actually issued by the 6502 is retained.
taps[#taps+1] = audiospace:install_read_tap(0x0800,0x0fff,"mtrap_audio_riot_read",function(a,d,mask) log("R",audio,a,d,mask,"audio",(a & 0x1f)<=3) end)
taps[#taps+1] = audiospace:install_write_tap(0x0800,0x0fff,"mtrap_audio_riot_write",function(a,d,mask) log("W",audio,a,d,mask,"audio",(a & 0x1f)<=3) end)
-- Observe main-CPU sound PIA traffic as context for commands generated by play.
taps[#taps+1] = mainspace:install_read_tap(0x5200,0x52ff,"mtrap_main_sound_read",function(a,d,mask) log("R",main,a,d,mask,"main",false) end)
taps[#taps+1] = mainspace:install_write_tap(0x5200,0x52ff,"mtrap_main_sound_write",function(a,d,mask) log("W",main,a,d,mask,"main",true) end)
_G.mtrap_voice_capture_taps = taps

local function field(port, name)
 local p=m.ioport.ports[port]; return p and p.fields[name] or nil
end
local coin=field(":IN0","Coin 1")
local start=field(":IN0","1 Player Start")
local dog=field(":IN0","Dog Button")
local right=field(":IN0","P1 Right")
local yellow=field(":IN2","Yellow Button")
local red=field(":IN2","Red Button")
local blue=field(":IN2","Blue Button")
if not coin or not start or not dog or not right or not yellow or not red or not blue then
 events:write("ERROR missing expected MAME input field\n")
 output:close(); events:close(); m:exit(); return
end
local schedule={
 {420,coin,1,"coin"},{445,coin,0,"coin_release"},
 {480,start,1,"start"},{510,start,0,"start_release"},
 {600,right,1,"right"},{720,right,0,"right_release"},
 {750,dog,1,"dog"},{780,dog,0,"dog_release"},
 {900,yellow,1,"yellow"},{930,yellow,0,"yellow_release"},
 {1050,red,1,"red"},{1080,red,0,"red_release"},
 {1200,blue,1,"blue"},{1230,blue,0,"blue_release"},
 {1500,right,1,"right_repeat"},{1740,right,0,"right_repeat_release"},
 {1800,dog,1,"dog_repeat"},{1860,dog,0,"dog_repeat_release"}
}
local si=1
emu.register_frame_done(function()
 local ok,err=pcall(function()
  frames=screen:frame_number()
  while si<=#schedule and frames>=schedule[si][1] do
   local e=schedule[si]; if frames==e[1] then e[2]:set_value(e[3]); events:write(string.format("input frame=%d control=%s asserted=%d\n",frames,e[4],e[3])) end
   si=si+1
  end
  if frames>=limit then
   events:write("complete frame="..frames.."\n")
   for k,v in pairs(counts) do events:write(string.format("count %s=%d\n",k,v)) end
   output:flush(); output:close(); events:flush(); events:close(); m:exit()
  end
 end)
 if not ok then events:write("ERROR callback="..tostring(err).."\n"); output:close(); events:close(); m:exit() end
end)
